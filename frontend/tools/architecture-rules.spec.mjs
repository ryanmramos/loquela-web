import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, test } from 'node:test';

import { findArchitectureViolations } from './architecture-rules.mjs';

const temporaryRoots = [];

afterEach(async () => {
  await Promise.all(
    temporaryRoots.splice(0).map((directory) => rm(directory, { recursive: true })),
  );
});

test('accepts imports within a feature and browser access through the adapter', async () => {
  const root = await createFrontend({
    'src/app/core/storage/browser-storage.ts': 'localStorage.getItem("tip");',
    'src/app/features/sources/source-list.ts': "import './source-state';",
    'src/app/features/sources/source-state.ts': 'export const ready = true;',
  });

  assert.deepEqual(await findArchitectureViolations(root), []);
});

test('rejects feature deep imports, shared feature imports, and direct generated clients', async () => {
  const root = await createFrontend({
    'src/app/api/generated/api.ts': '// Generated by ng-openapi-gen\nexport class Api {}',
    'src/app/features/cards/card-page.ts':
      "import { Api } from '@api/generated/api';\n@Component({}) export class CardPage {}",
    'src/app/features/sources/source-page.ts': "import '../cards/private/card-state';",
    'src/app/shared/source-label.ts': "import '../features/sources/source-state';",
  });

  const violations = await findArchitectureViolations(root);

  assert.equal(violations.length, 3);
  assert.ok(violations.some((violation) => violation.includes('components must not import')));
  assert.ok(violations.some((violation) => violation.includes('deep-imports feature')));
  assert.ok(violations.some((violation) => violation.includes('shared code must not import')));
});

test('rejects unreviewed storage, sanitizer bypasses, and hand-authored generated files', async () => {
  const root = await createFrontend({
    'src/app/api/generated/manual.ts': 'export const value = 1;',
    'src/app/core/unsafe.ts':
      "sessionStorage.setItem('token', 'secret');\nsan.bypassSecurityTrustHtml(value);",
  });

  const violations = await findArchitectureViolations(root);

  assert.equal(violations.length, 3);
  assert.ok(violations.some((violation) => violation.includes('browser storage')));
  assert.ok(violations.some((violation) => violation.includes('sanitizer bypass')));
  assert.ok(violations.some((violation) => violation.includes('generator marker')));
});

async function createFrontend(files) {
  const root = await mkdtemp(path.join(tmpdir(), 'loquela-architecture-'));
  temporaryRoots.push(root);

  await Promise.all(
    Object.entries(files).map(async ([relativePath, content]) => {
      const file = path.join(root, relativePath);
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, content, 'utf8');
    }),
  );

  return root;
}
