import { readFile, readdir } from 'node:fs/promises';
import path from 'node:path';

const IMPORT_PATTERN = /(?:from\s+|import\s+|import\s*\()\s*['"](?<specifier>[^'"]+)['"]/gu;
const STORAGE_PATTERN =
  /\b(?:localStorage|sessionStorage)\b|(?:globalThis|window)\.(?:localStorage|sessionStorage)/u;
const SANITIZER_BYPASS_PATTERN = /\bbypassSecurityTrust[A-Za-z]*\s*\(/u;
const GENERATED_MARKER_PATTERN = /auto-generated|generated by ng-openapi-gen/iu;

export async function findArchitectureViolations(frontendRoot) {
  const appRoot = path.join(frontendRoot, 'src', 'app');
  const files = await collectFiles(appRoot);
  const violations = [];

  for (const file of files.filter((candidate) => candidate.endsWith('.ts'))) {
    const source = await readFile(file, 'utf8');
    const normalizedFile = normalize(file);
    const relativeFile = normalize(path.relative(frontendRoot, file));
    const sourceFeature = featureName(normalizedFile);

    if (
      STORAGE_PATTERN.test(source) &&
      !relativeFile.endsWith('src/app/core/storage/browser-storage.ts')
    ) {
      violations.push(`${relativeFile}: browser storage access is restricted to BrowserStorage`);
    }

    if (SANITIZER_BYPASS_PATTERN.test(source)) {
      violations.push(`${relativeFile}: Angular sanitizer bypass calls require security review`);
    }

    if (
      normalizedFile.includes('/src/app/api/generated/') &&
      !GENERATED_MARKER_PATTERN.test(source)
    ) {
      violations.push(`${relativeFile}: generated API source is missing a generator marker`);
    }

    for (const specifier of importSpecifiers(source)) {
      const target = resolveImport(file, specifier, appRoot);
      if (!target) {
        continue;
      }

      const targetFeature = featureName(target);
      if (
        sourceFeature &&
        targetFeature &&
        sourceFeature !== targetFeature &&
        isFeatureDeepImport(target, appRoot, targetFeature)
      ) {
        violations.push(
          `${relativeFile}: feature "${sourceFeature}" deep-imports feature "${targetFeature}"`,
        );
      }

      if (normalizedFile.includes('/src/app/shared/') && target.includes('/src/app/features/')) {
        violations.push(`${relativeFile}: shared code must not import feature code`);
      }

      if (/@Component\s*\(/u.test(source) && target.includes('/src/app/api/generated/')) {
        violations.push(`${relativeFile}: components must not import generated API clients`);
      }
    }
  }

  return violations.sort();
}

async function collectFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map((entry) => {
      const target = path.join(directory, entry.name);
      return entry.isDirectory() ? collectFiles(target) : [target];
    }),
  );
  return nested.flat();
}

function importSpecifiers(source) {
  return [...source.matchAll(IMPORT_PATTERN)]
    .map((match) => match.groups?.['specifier'])
    .filter((specifier) => specifier !== undefined);
}

function resolveImport(sourceFile, specifier, appRoot) {
  if (specifier === '@app' || specifier.startsWith('@app/')) {
    return normalize(path.join(appRoot, specifier.slice('@app'.length)));
  }
  if (specifier === '@core' || specifier.startsWith('@core/')) {
    return normalize(path.join(appRoot, 'core', specifier.slice('@core'.length)));
  }
  if (specifier === '@api' || specifier.startsWith('@api/')) {
    return normalize(path.join(appRoot, 'api', specifier.slice('@api'.length)));
  }
  if (specifier.startsWith('.')) {
    return normalize(path.resolve(path.dirname(sourceFile), specifier));
  }
  return undefined;
}

function featureName(file) {
  return file.match(/\/src\/app\/features\/(?<feature>[^/]+)/u)?.groups?.['feature'];
}

function isFeatureDeepImport(target, appRoot, targetFeature) {
  const featureRoot = normalize(path.join(appRoot, 'features', targetFeature));
  return target !== featureRoot && target !== `${featureRoot}/index`;
}

function normalize(value) {
  return value.split(path.sep).join('/');
}
